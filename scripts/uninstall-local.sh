#!/bin/sh
# Undoes scripts/install-local.sh: removes the installed imgwand binary and everything the binary and the local build
# left on this machine.
#
#   sh scripts/uninstall-local.sh               # remove the binary, PATH lines, native caches and build outputs
#   sh scripts/uninstall-local.sh --dry-run     # only show what would be removed
#   sh scripts/uninstall-local.sh --purge       # also remove your config (~/.config/imgwand)
#   sh scripts/uninstall-local.sh --keep-build  # leave this repository's build outputs alone
#
# Removes, via uninstall.sh: the binary (from $IMGWAND_INSTALL_DIR, ~/.local/bin, /usr/local/bin or wherever it is
# on PATH; only if it really is imgwand), PATH lines install.sh added, the native library caches. Then, in this
# repository: dist/ (built binaries), .native/ (cross-installed sharp, downloaded and musl-built C2PA SDKs, generated
# assets) and .imgwand-tmp/ (scratch files). Never touches node_modules, your signing keys, or anything else.
set -eu

dry="" purge="" keep_build=""
for arg do
  case $arg in
    -n | --dry-run) dry=1 ;;
    --purge) purge=1 ;;
    --keep-build) keep_build=1 ;;
    -h | --help) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown option: $arg (see --help)" >&2; exit 2 ;;
  esac
done

root=$(cd "$(dirname "$0")/.." && pwd)

# 1. What is installed on the machine: the same logic as the public uninstaller, so both stay in step.
status=0
sh "$root/uninstall.sh" ${dry:+--dry-run} ${purge:+--purge} || status=$?

# 2. What the local build left in this repository (all of it is regenerated by the next build).
if [ -z "$keep_build" ]; then
  removed=""
  for dir in dist .native .imgwand-tmp; do
    path="$root/$dir"
    [ -e "$path" ] || continue
    size=$(du -sh "$path" 2>/dev/null | cut -f1)
    if [ -n "$dry" ]; then
      echo "→ Would remove build output $dir/ ($size)" >&2
    elif rm -rf "$path" && [ ! -e "$path" ]; then
      echo "✓ Removed build output $dir/ ($size)" >&2
      removed=1
    else
      echo "✗ Could not remove $path" >&2
      status=1
    fi
  done
  [ -n "$removed" ] || [ -n "$dry" ] || echo "→ No build outputs to remove in $root" >&2
fi

exit "$status"
